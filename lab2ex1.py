def translate(seq):
    seq = seq.upper().replace("U", "T")
    start = seq.find("ATG")
    if start == -1:
        return "No start codon found"
    protein = ""
    for i in range(start, len(seq) - 2, 3):
        aa = genetic_code[seq[i:i + 3]]
        if aa == "Stop":
            break
        protein += aa
    return protein


